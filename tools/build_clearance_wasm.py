"""Regenerate the portable separating-axis kernel with LLVM clang and wasm-ld."""
from pathlib import Path
import base64, subprocess, tempfile
root=Path(__file__).resolve().parents[1]
with tempfile.TemporaryDirectory() as out:
    obj=Path(out)/'kernel.o'
    wasm=Path(out)/'kernel.wasm'
    subprocess.run(['clang','--target=wasm32','-O3','-ffreestanding','-ffp-contract=off','-c',
                    root/'engine/clearance_cert.c','-o',obj],check=True)
    subprocess.run(['wasm-ld','--no-entry','--strip-all','--export=__heap_base','--export=prepare',
                    '--export=separation','--export=mesh_bytes','--export=vertex_offset','--export=required_tip','--export=tip_blocks',obj,'-o',wasm],check=True)
    data=base64.b64encode(wasm.read_bytes()).decode('ascii')
    (root/'viewer/clearance-wasm.mjs').write_text(
        '// Generated by tools/build_clearance_wasm.py from engine/clearance_cert.c.\n'
        +'export default "'+data+'";\n',encoding='utf8')
